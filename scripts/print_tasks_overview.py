NUM_SHOTS = 3


def _slug(name: str) -> str:
    return name.replace(":", "_").replace(" ", "_")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default="tasks_overview.md",
                        help="Output markdown file (default: tasks_overview.md)")
    args = parser.parse_args()

    discover_tasks()

    lines = []
    lines.append("# ElementalTask — Task Overview\n")
    lines.append(
        "Each task is shown with a few-shot prompt (demonstrations) "
        f"followed by one query and its expected answer.\n"
    )
    lines.append(f"> Generated by `scripts/print_tasks_overview.py`\n")
    lines.append("---\n")

    # Group by category for clean presentation
    by_category: dict[str, list[str]] = {}
    for task_name in ALL_TASKS:
        cat = CATEGORY_MAP.get(task_name, "Other")
        by_category.setdefault(cat, []).append(task_name)

    category_order = [
        "Arithmetic", "String Manipulation", "Translation", "Grammatical",
        "Factual Lookup", "Vocabulary", "Pattern Recognition",
        "Associative Memory", "Logic", "Reading Comprehension",
        "Compositional", "Other",
    ]

    failed = []
    succeeded = 0

    for cat in category_order:
        task_names = by_category.get(cat, [])
        if not task_names:
            continue

        lines.append(f"\n## {cat}\n")

        for task_name in task_names:
            lines.append(f"\n### `{task_name}`\n")

            try:
                task = get_task(task_name)
            except Exception as e:
                lines.append(f"_⚠ Could not load task: {e}_\n")
                failed.append((task_name, str(e)))
                continue

            # Get examples
            try:
                examples = task.get_icl_examples(num_examples=NUM_SHOTS, seed=42)
                test_rows = task.get_split("test")
                if not test_rows:
                    lines.append("_⚠ No test instances available._\n")
                    failed.append((task_name, "empty test split"))
                    continue

                # Pick a query instance that isn't one of the demo examples
                demo_inputs = {ex["input"] for ex in examples}
                query = next(
                    (r for r in test_rows
                     if r.get(task.config.input_column, "") not in demo_inputs),
                    test_rows[0],
                )

                # Build formatted prompt
                prompt = task.build_prompt(query, num_shots=NUM_SHOTS)
                answer = str(query.get(task.config.output_column, ""))

                lines.append("```\n")
                lines.append(prompt.rstrip() + "\n")
                lines.append("```\n")
                lines.append(f"\n**Expected answer:** `{answer}`\n")
                succeeded += 1

            except Exception as e:
                lines.append(f"_⚠ Error generating example: {e}_\n")
                failed.append((task_name, str(e)))

    # Footer
    lines.append("\n---\n")
    lines.append(f"\n**{succeeded}/{len(ALL_TASKS)} tasks successfully rendered.**\n")
    if failed:
        lines.append("\n### Failed tasks\n\n")
        for name, err in failed:
            lines.append(f"- `{name}`: {err}\n")

    out_path = Path(args.output)
    out_path.write_text("".join(lines))
    print(f"✓ Saved task overview ({succeeded}/{len(ALL_TASKS)} tasks) → {out_path}")


if __name__ == "__main__":
    main()
